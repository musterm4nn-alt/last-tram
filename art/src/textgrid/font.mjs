export function textWidth(str) {
  let w = 0;
  for (const ch of str) w += (GLYPHS[ch] ?? GLYPHS[' '])[0].length + 1;
  return Math.max(0, w - 1);
}

/** Writes `str` with its top-left corner at (x, y). */
export function text(img, str, x, y, color) {
  let cx = x;
  for (const ch of str) {
    const g = GLYPHS[ch] ?? GLYPHS[' '];
    g.forEach((row, j) => {
      for (let i = 0; i < row.length; i++) if (row[i] === '#') img.px(cx + i, y + j, color);
    });
    cx += g[0].length + 1;
  }
}
